# -*- coding: utf-8 -*-
"""答案准确性审查（2026-08-24）发现的错误修正脚本
逐条审查911题后，对以下题目的事实性错误进行修正。
"""
import json

PATH = 'src/assets/data/all_questions.json'
with open(PATH, encoding='utf-8') as f:
    data = json.load(f)

by_id = {q['id']: q for q in data}

fixes = []

def fix(qid, new_q=None, new_a=None, note=''):
    q = by_id[qid]
    assert q['answer'] is True, f"{qid} 预期答案为○"
    if new_q:
        q['question'] = new_q
    if new_a:
        q['explanation'] = new_a
    fixes.append((qid, note))

# 1. 违规点数累计期间：过去3年（非1年）
fix('q_0664',
    new_q='驾驶人的违规点数在过去的 3 年内累计达到规定数量时，将受到停止驾驶（免许停止）的行政处分。',
    new_a='违规点数按过去3年内的违规行为累计计算，达到处分基准点数即受免许停止或取消处分。')

# 2. 超速点数：25以上30未满为3点
fix('q_0666',
    new_q='一般道路上超速 25km/h 以上、30km/h 未满时，违规点数为 3 点。',
    new_a='超速点数分档：25km/h未满记1点、20-25记2点（部分区间）、25-30未满记3点、30以上40未满记6点、50以上60未满记12点、60以上记15点。')

# 3. 一般道路超速50+是免停90日；一发取消是60+（高速等50+）
fix('q_0667',
    new_q='在高速公路上超速 50km/h 以上属于严重违规，将被吊销驾照（取消处分）。',
    new_a='高速公路上超速50km/h以上构成"一発取消"（吊销驾照）；一般道路则为60km/h以上。一般道路超速50km/h以上60km/h未满记12点，处90日免停。')

# 4. 酒醉驾驶标准：呼气0.40mg/L（非0.3）
fix('q_0671',
    new_q='醉酒状态驾驶（酒醉驾驶）比饮酒驾驶处罚更重，且提供酒水、车辆或同乘的人也会受到处罚。',
    new_a='酒醉驾驶指呼气1L中酒精浓度0.40mg/L以上（或血液1ml中0.08mg以上）无法正常驾驶的状态，处罚最重，且牵连提供车辆者、劝酒者与同乘者。')

# 5. 危险驾驶致死伤：伤害15年以下、死亡1年以上20年以下
fix('q_0675',
    new_q='危险驾驶致人受伤的，可被判处 15 年以下有期徒刑；致人死亡的，可被判处 1 年以上 20 年以下有期徒刑。',
    new_a='危险驾驶致死伤罪：致人负伤处15年以下懲役，致人死亡处1年以上20年以下有期懲役（无照驾驶时加重）。')

# 6. 手持手机刑事罚自2019.12已有，2024.11是反则金上调
fix('q_0677',
    new_q='驾驶中手持手机通话或操作（ながら運転）可被处以 6 个月以下惩役或 10 万日元以下罚金。',
    new_a='手持手机使用属刑事罚对象行为（2019年12月改正引入）；2024年11月改正进一步上调了反则金金额。')

# 7. 有效期超过1年是"失效"，失效后3年才"取消"
fix('q_0680',
    new_q='驾照有效期届满后超过 1 年仍未办理更新手续的，驾照将失效（失效后再经过 3 年则被取消）。',
    new_a='有效期超过1年未更新→驾照失効（失去效力，需重新考试才能恢复）；失効后3年经→取消处分。')

# 8. 踏切前30m禁止的是超车/变更车道；驻停禁令是侧方10m
fix('q_0686',
    new_q='在踏切内及踏切前方 30 米以内，禁止追越和变更车道。',
    new_a='踏切及其前方30m以内是法定禁止追越场所；驻停车禁令区域则是踏切及其侧方10m以内。')

# 9. 踏切驻停禁令距离是10米（不是5米）
fix('q_0693',
    new_q='在铁路道口（踏切）及其侧方 10 米以内的区域，禁止长时停车和临时停车。',
    new_a='踏切及其侧方10m以内全面禁止驻停（交差点为5m、横断步道前后为5m、公交站为10m）。')

# 10. 普通二轮定义：50cc超~400cc以下（125cc界限不存在于准驾划分）
fix('q_0725',
    new_q='普通两轮摩托车是指排气量超过 50cc 且 400cc 以下的二轮汽车（电动则额定功率超过 0.6kW 且 20kW 以下），需要普通两轮摩托车驾照。',
    new_a='二轮驾照划分：原付50cc以下/0.6kW以下；普通二轮50cc超～400cc以下；大型二轮400cc超或20kW超。')

# 11. 路面速度数字标示：去掉颜色断言（官方标示为白色，避免误导）
for qid in ('q_img_pdf_marking_speed_limit_30_t', 'q_img_pdf_marking_speed_limit_30_f'):
    by_id[qid]['question'] = by_id[qid]['question'].replace('黄色速度数字', '速度数字')
    by_id[qid]['explanation'] = by_id[qid]['explanation'].replace('黄色速度数字', '速度数字')
    fixes.append((qid, '去除路面标示颜色断言'))

with open(PATH, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, separators=(',', ':'))

print(f'共修正 {len(fixes)} 处：')
for qid, note in fixes:
    print(f'  {qid}: {note}')
